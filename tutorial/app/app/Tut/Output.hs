-- | Marking up the program output for the docs.
--
-- If the environment variable @TUT_SNIPPETS@ is set, 'section' surrounds the
-- output of an action with @--8<-- [start:name]@ / @--8<-- [end:name]@ markers.
-- @make tut-run@ saves this output to @tutorial/out/tutorial.txt@,
-- and the chapters include it via @pymdownx.snippets@:
--
-- > --8<-- "out/tutorial.txt:name"
--
-- Without the variable only a section header is printed,
-- so the output is easy to read in a console.
module Tut.Output (section, formatSql, sqlSection) where

import Control.Exception (finally)
import Data.Char (isSpace, toLower)
import Data.Text (Text)
import Data.Text qualified as T
import System.Environment (lookupEnv)

section :: String -> IO a -> IO a
section name act = do
  marked <- maybe False (not . null) <$> lookupEnv "TUT_SNIPPETS"
  if marked
    then do
      putStrLn $ "--8<-- [start:" <> name <> "]"
      act `finally` putStrLn ("--8<-- [end:" <> name <> "]")
    else do
      putStrLn $ "\n--- " <> name
      act

-- | Format SQL generated by pg-schema for humans.
--
-- Each part of a statement (@select@, @from@, @where@, @order by@, @values@,
-- @set@, @on conflict@, @returning@, …) starts a new line, columns of the
-- @select@ list and assignments in @set@ go one per line, subqueries are
-- indented.
--
-- This is a simple formatter for the examples in the docs, not an SQL parser:
-- it only looks at parentheses, quotes and keywords. Text that already has
-- line breaks (e.g. plpgsql functions of @*JSON@) is left as is.
formatSql :: Text -> Text
formatSql sql
  | T.any (== '\n') (T.strip sql) = sql
  | otherwise = T.pack $ render $ tokens $ T.unpack sql
  where
    -- Tokens: quoted strings, parentheses, commas, spaces and other words.
    tokens :: String -> [String]
    tokens [] = []
    tokens (c : cs)
      | c `elem` ("'\"" :: String) =
          let (q, rest) = break (== c) cs
          in (c : q <> take 1 rest) : tokens (drop 1 rest)
      | c `elem` ("()," :: String) = [c] : tokens cs
      | isSpace c = " " : tokens (dropWhile isSpace cs)
      | otherwise =
          let (w, rest) = break (\x -> isSpace x || x `elem` ("()',\"" :: String)) (c : cs)
          in w : tokens rest

    render :: [String] -> String
    render = go 0 [] "" 0

    -- State: parenthesis depth, stack of open statements (depth, indent,
    -- current part of the statement), previous word and current line indent.
    go :: Int -> [(Int, Int, String)] -> String -> Int -> [String] -> String
    go _ _ _ _ [] = ""
    go d sts prev ind (t : ts)
      | t == " " = case ts of
          (n : rest) | startsStmt sts (lower n) || breaks d sts prev (lower n) (nextWord rest) -> go d sts prev ind ts
          _ -> " " <> go d sts prev ind ts
      | startsStmt sts w =
          let ind' = if null sts then 0 else ind + 4
              pre = if null sts then "" else nl ind'
          in pre <> t <> go d ((d, ind', w) : sts) w ind' ts
      | breaks d sts prev w (nextWord ts), ((sd, si, _) : rest) <- sts =
          nl si <> t <> go d ((sd, si, w) : rest) w si ts
      | t == ",", ((sd, si, cl) : _) <- sts, sd == d, Just k <- lookup cl listIndent =
          "," <> nl (si + k) <> go d sts prev (si + k) (dropWhile (== " ") ts)
      | t == "(" = t <> go (d + 1) sts prev ind ts
      | t == ")" =
          let sts' = case sts of
                ((sd, _, _) : rest) | sd == d -> rest
                _ -> sts
          in t <> go (d - 1) sts' prev ind ts
      | otherwise = t <> go d sts (if all isSpace t then prev else w) ind ts
      where
        w = lower t

    startsStmt sts w = w `elem` ["select", "insert", "update", "delete"]
      && not (w == "update" && inClause "on" sts)

    -- Line break before a part of a statement at the statement's own depth.
    -- @next@ is the next word (to tell @on conflict@ from @join … on@ and
    -- @distinct on@).
    breaks d sts prev w next = case sts of
      ((sd, _, cl) : _) -> sd == d && w `elem` clauses
        && not (w == "from" && prev `elem` ["delete", "distinct"])
        && not (w == "set" && cl == "on")
        && not (w == "on" && next /= "conflict")
        && not (w == "join" && prev `elem` joinMods)
        && not (w `elem` joinMods && prev `elem` joinMods)
      [] -> False

    joinMods = ["left", "right", "full", "inner", "outer", "cross"]

    nextWord = \case
      (" " : rest) -> nextWord rest
      (x : _) -> lower x
      [] -> ""

    inClause c = \case
      ((_, _, cl) : _) -> cl == c
      [] -> False

    clauses =
      [ "from", "where", "order", "group", "having", "limit", "offset"
      , "values", "set", "on", "returning"
      , "join", "left", "right", "full", "inner", "cross" ]

    -- Indent of list items relative to the start of the statement.
    listIndent = [("select", 7), ("set", 4)]

    nl n = "\n" <> replicate n ' '

    lower = map toLower

-- | Formatted SQL of an example: a separate section @<name>-sql@.
-- A chapter shows it in a collapsible block right after the example output.
sqlSection :: String -> [Text] -> IO ()
sqlSection name sqls = section (name <> "-sql") $
  putStrLn $ T.unpack $ T.intercalate (T.pack "\n\n") (terminate . formatSql . T.strip <$> sqls)
  where
    terminate q = if T.isSuffixOf (T.pack ";") q then q else q <> T.pack ";"
